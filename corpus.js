/* 双通道检索：①要素标签命中（本轮/本菌株的权威案例）②用户发言词面重合。
 * 输出 top-k，并保证至少 1 条来自同一大类——接地不再依赖运气。 */
function retrieveGrounding(userText, opts = {}) {
  const k = opts.k || 3;
  const elements = opts.elements || [];           // 本轮 watch 涉及的话术要素
  const strain = opts.strain || "";               // 剧本所属骗术大类
  const t = (userText || "").toLowerCase();
  const grams = new Set();
  for (let n = 2; n <= 4; n++) for (let i = 0; i + n <= t.length; i++) grams.add(t.slice(i, i + n));
  const scored = CORPUS.map((c, idx) => {
    let s = 0;
    const ct = c.text.toLowerCase();
    grams.forEach(g => { if (g.length >= 2 && ct.includes(g)) s += g.length; });
    const els = c.el ? c.el.split(",") : [];
    els.forEach(el => { if (elements.includes(el)) s += 6; });   // 要素对齐：本轮正在用的机关
    if (strain && c.strain === strain) s += 3;                   // 同大类优先
    return { c, idx, s };
  });
  const picked = scored.filter(x => x.s >= 4).sort((a, b) => b.s - a.s).slice(0, k).map(x => x.c);
  if (!picked.length) {                                          // 兜底：同大类前 k 条，接地永不为空
    const same = CORPUS.filter(c => c.strain === strain);
    return (same.length ? same : CORPUS).slice(0, k);
  }
  if (!picked.some(c => c.strain === strain)) {
    const same = CORPUS.filter(c => c.strain === strain);
    if (same[0]) { picked.pop(); picked.unshift(same[0]); }
  }
  return picked;
}

